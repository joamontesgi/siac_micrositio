  <section class="band">
    <div class="wrap">
      <span class="kicker">Marco nacional</span>
      <div class="grid" style="gap:12px">
        <div class="norm"><div class="ref">Ley 1188 de 2008<span>Congreso de la República</span></div><p>Regula el registro calificado de los programas de educación superior. Es la ley que desarrollan los decretos siguientes.</p></div>
        <div class="norm"><div class="ref">Decreto 1075 de 2015<span>Modificado por el Decreto 1330 de 2019</span></div><p>Establece la cultura de la autoevaluación como condición de calidad y dispone que toda institución cuente con un SIAC que contemple, al menos, sistemas de información, mecanismos de seguimiento al cumplimiento de condiciones de calidad, participación de las comunidades académicas, articulación con la planeación estratégica institucional y procesos continuos de autoevaluación y autorregulación.<blockquote>«La institución deberá contar con un sistema interno de aseguramiento de la calidad». Decreto 1330 de 2019, artículo 2.5.3.2.3.1.4</blockquote></p></div>
        <div class="norm"><div class="ref">Acuerdo 01 de 2025<span>Consejo Nacional de Educación Superior, CESU</span></div><p>Actualiza el Modelo de Aseguramiento en Alta Calidad. Reconoce el mejoramiento continuo y la autorregulación como factores clave de la evaluación institucional y exige ahora un SIAC consolidado, maduro y articulado con la planeación, a través del cual se evidencien los ejercicios internos de aseguramiento.</p></div>
        <div class="norm"><div class="ref">Plan de Fomento a la Calidad<span>Decreto 1075 de 2015, artículo 2.5.4.3.4</span></div><p>Contempla como línea de inversión el fortalecimiento y la consolidación de los sistemas internos de aseguramiento de la calidad, para armonizar registro calificado y acreditación y para apoyar los planes de mejoramiento.</p></div>
        <div class="norm"><div class="ref">Plan Nacional de Desarrollo 2022-2026<span>«Colombia Potencia Mundial de la Vida»</span></div><p>Plantea la reconceptualización del sistema de aseguramiento de la calidad en la educación superior, con el fortalecimiento de los SIAC para fomentar la autoevaluación, la autorregulación y la autonomía institucional.</p></div>
      </div>
      <span class="kicker" style="margin-top:30px">Régimen propio de la Universidad Nacional</span>
      <div class="grid" style="gap:12px">
        <div class="norm"><div class="ref">Decreto 1210 de 1993<span>Régimen orgánico especial</span></div><p>Asigna a la Universidad el mandato de desarrollar la educación superior en el país con fundamento en la excelencia, y le otorga el régimen de autonomía con el que cumple esa misión como institución pública, nacional y autónoma.</p></div>
        <div class="norm"><div class="ref">Acuerdo 011 de 2005<span>Consejo Superior Universitario</span></div><p>Formaliza ese régimen de autonomía. La autonomía académica incluye la facultad de definir su propio sistema de evaluación interno y de decidir sobre su evaluación externa con fines de acreditación.</p></div>
        <div class="norm"><div class="ref">Acuerdo 151 de 2014<span>Consejo Superior Universitario</span></div><p>Establece la autoevaluación como un proceso participativo, académico y reflexivo, orientado al mejoramiento de los programas curriculares y al logro de la excelencia académica. Es la norma que el SIAC se propone actualizar.</p></div>
        <div class="norm"><div class="ref">Acuerdos 29 de 2004 y 030 de 2007<span>Consejo Superior Universitario</span></div><p>Adoptan, respectivamente, la acreditación de programas curriculares ante el Consejo Nacional de Acreditación y la acreditación institucional.</p></div>
        <div class="norm"><div class="ref">Acuerdo 015 de 2023<span>Consejo Superior Universitario</span></div><p>Proyecta el Plan de Fomento a la Calidad de la Universidad, dentro del cual se inscribe la consolidación del SIAC.</p></div>
